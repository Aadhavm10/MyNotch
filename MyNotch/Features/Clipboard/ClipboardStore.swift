import AppKit
import Observation

struct ClipItem: Identifiable, Codable, Hashable {
    enum Kind: String, Codable { case text, image, files }

    let id: UUID
    let kind: Kind
    var text: String?
    /// Rich-text version of `text`, kept so formatting survives a re-copy (small items only).
    var rtf: Data?
    var filePaths: [String]?
    /// PNG saved in ClipboardStore.imageDirectory.
    var imageFileName: String?
    var sourceBundleID: String?
    var date: Date
    var pinned = false

    var imageURL: URL? { imageFileName.map { ClipboardStore.imageDirectory.appendingPathComponent($0) } }

    /// A single-line http(s) link, shown with a link icon and its host.
    var link: URL? {
        guard kind == .text, let text = text?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.contains(where: \.isWhitespace),
              let url = URL(string: text), ["http", "https"].contains(url.scheme?.lowercased() ?? ""), url.host != nil
        else { return nil }
        return url
    }

    /// Hex colors like #FF8800 or #f80 get a swatch.
    var color: NSColor? {
        guard kind == .text, var hex = text?.trimmingCharacters(in: .whitespacesAndNewlines), hex.hasPrefix("#") else { return nil }
        hex.removeFirst()
        if hex.count == 3 { hex = hex.map { "\($0)\($0)" }.joined() }
        guard hex.count == 6, let value = UInt32(hex, radix: 16) else { return nil }
        return NSColor(
            srgbRed: CGFloat((value >> 16) & 0xFF) / 255,
            green: CGFloat((value >> 8) & 0xFF) / 255,
            blue: CGFloat(value & 0xFF) / 255,
            alpha: 1
        )
    }
}

/// Watches the general pasteboard and keeps a history of what was copied.
/// macOS has no pasteboard-change notification, so it polls `changeCount` (cheap: an integer read).
@Observable
final class ClipboardStore {
    static let shared = ClipboardStore()

    static let directory = TrayStore.rootDirectory.appendingPathComponent("Clipboard")
    static let imageDirectory = directory.appendingPathComponent("Images")
    private static let indexURL = directory.appendingPathComponent("clipboard.json")

    /// Pasteboard markers set by password managers and similar apps (see nspasteboard.org).
    private static let privateTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]
    private static let maxImageBytes = 20 * 1024 * 1024
    private static let maxRTFBytes = 512 * 1024

    /// Pinned first, then newest first.
    private(set) var items: [ClipItem] = []
    /// Briefly set after an item is copied back, for the "Copied" badge.
    private(set) var lastCopiedID: UUID?

    private let settings = SettingsStore.shared
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    private init() {
        lastChangeCount = pasteboard.changeCount
        try? FileManager.default.createDirectory(at: Self.imageDirectory, withIntermediateDirectories: true)
        if settings.clipboard.persist,
           let data = try? Data(contentsOf: Self.indexURL),
           let saved = try? JSONDecoder().decode([ClipItem].self, from: data)
        {
            items = saved
        } else {
            removeAllFiles(keeping: [])
        }
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    // MARK: Capturing

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard settings.clipboard.enabled else { return }

        let types = pasteboard.types ?? []
        if types.contains(where: Self.privateTypes.contains) { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, settings.clipboard.ignoredBundleIDs.contains(source) { return }

        if let item = capture(types: types, source: source) {
            insert(item)
        }
    }

    private func capture(types: [NSPasteboard.PasteboardType], source: String?) -> ClipItem? {
        // Finder files first: a copied file also carries its name as a string.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty
        {
            return ClipItem(id: UUID(), kind: .files, filePaths: urls.map(\.path), sourceBundleID: source, date: .now)
        }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let rtf = pasteboard.data(forType: .rtf).flatMap { $0.count <= Self.maxRTFBytes ? $0 : nil }
            return ClipItem(id: UUID(), kind: .text, text: text, rtf: rtf, sourceBundleID: source, date: .now)
        }
        if types.contains(.png) || types.contains(.tiff),
           let image = NSImage(pasteboard: pasteboard),
           let tiff = image.tiffRepresentation,
           let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]),
           png.count <= Self.maxImageBytes
        {
            let id = UUID()
            let name = "\(id.uuidString).png"
            do {
                try png.write(to: Self.imageDirectory.appendingPathComponent(name))
            } catch {
                return nil
            }
            return ClipItem(id: id, kind: .image, imageFileName: name, sourceBundleID: source, date: .now)
        }
        return nil
    }

    private func insert(_ item: ClipItem) {
        // Copying the same thing again moves it to the top instead of duplicating it.
        var item = item
        if let existing = items.firstIndex(where: { $0.kind == item.kind && $0.kind != .image && $0.text == item.text && $0.filePaths == item.filePaths }) {
            item.pinned = items[existing].pinned
            items.remove(at: existing)
        }
        items.insert(item, at: 0)
        sortAndTrim()
        save()
    }

    // MARK: Actions

    /// Puts an item back on the clipboard, ready to paste, and moves it to the top.
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            if let rtf = item.rtf { pasteboard.setData(rtf, forType: .rtf) }
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let url = item.imageURL, let image = NSImage(contentsOf: url) { pasteboard.writeObjects([image]) }
        case .files:
            let urls = (item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            pasteboard.writeObjects(urls)
        }
        // Our own write shouldn't be captured as a new entry.
        lastChangeCount = pasteboard.changeCount

        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = .now
            items.insert(moved, at: 0)
            sortAndTrim()
            save()
        }
        lastCopiedID = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.lastCopiedID == item.id { self?.lastCopiedID = nil }
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        sortAndTrim()
        save()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        if let url = item.imageURL { try? FileManager.default.removeItem(at: url) }
        save()
    }

    /// Clears the history. Pinned items stay unless `includingPinned` is true.
    func removeAll(includingPinned: Bool = false) {
        items = includingPinned ? [] : items.filter(\.pinned)
        removeAllFiles(keeping: items)
        save()
    }

    /// Called when "remember after restart" changes.
    func persistenceChanged() {
        if settings.clipboard.persist { save() } else { try? FileManager.default.removeItem(at: Self.indexURL) }
    }

    func sortAndTrim() {
        let pinned = items.filter(\.pinned)
        var unpinned = items.filter { !$0.pinned }
        let limit = max(settings.clipboard.maxItems, 1)
        if unpinned.count > limit {
            unpinned.suffix(from: limit).compactMap(\.imageURL).forEach { try? FileManager.default.removeItem(at: $0) }
            unpinned = Array(unpinned.prefix(limit))
        }
        items = pinned + unpinned
    }

    // MARK: Storage

    private func save() {
        guard settings.clipboard.persist else { return }
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: Self.indexURL, options: .atomic)
    }

    private func removeAllFiles(keeping kept: [ClipItem]) {
        let keep = Set(kept.compactMap(\.imageFileName))
        let files = (try? FileManager.default.contentsOfDirectory(atPath: Self.imageDirectory.path)) ?? []
        for file in files where !keep.contains(file) {
            try? FileManager.default.removeItem(at: Self.imageDirectory.appendingPathComponent(file))
        }
    }
}
